"""Security policy evaluation engine for AI Banking Agent.

This module exports evaluate_action, a pure, fail-closed function that evaluates
proposed banking actions against security policies according to frozen contracts v1.0.0.
"""
import logging
from decimal import Decimal
from typing import Any

from pydantic import ValidationError

from contracts.enums import Tier, ToolName
from contracts.models import ActionProposal, BankingContext, PolicyDecision
from contracts.tool_schemas import validate_tool_arguments

from .rules import (
    DEFAULT_CONFIG,
    PolicyConfig,
    SecurityReasonCode,
    is_mutation_tool,
    is_read_only_tool,
    make_rejection_decision,
)

logger = logging.getLogger(__name__)


def evaluate_action(
    proposal: ActionProposal,
    context: BankingContext,
    config: PolicyConfig = DEFAULT_CONFIG,
) -> PolicyDecision:
    """Evaluate whether an ActionProposal satisfies banking security policy.

    This is a PURE, FAIL-CLOSED policy evaluation function:
    - Never mutates the input proposal or context.
    - Never throws an unhandled exception to the caller.
    - If any argument, field, or condition is invalid, returns a fail-closed PolicyDecision
      (allowed_to_proceed=False, tier=Tier.RED).

    Tiers:
    - Tier.GREEN: Read-only actions (get_balance, analyze_spending, list_subscriptions).
      Allowed to proceed without explicit confirmation or MFA.
    - Tier.YELLOW: Low/standard-risk state mutations (cumulative transfers <= CNY 1000,
      subscription cancellation). Requires explicit user confirmation.
    - Tier.RED: High-risk mutations (cumulative transfers > CNY 1000). Requires confirmation
      and simulated MFA. Also used for policy rejections/violations (allowed_to_proceed=False).

    Parameters:
        proposal: The ActionProposal generated by the agent.
        context: The authenticated BankingContext provided by the backend.
        config: Optional PolicyConfig for threshold customization (defaults to frozen spec).

    Returns:
        PolicyDecision conforming to contracts.models.PolicyDecision.
    """
    try:
        # Step 1: Validate input object types (Fail-closed on malformed or missing objects)
        if proposal is None or not isinstance(proposal, ActionProposal):
            return make_rejection_decision(SecurityReasonCode.INVALID_PROPOSAL)

        if context is None or not isinstance(context, BankingContext):
            return make_rejection_decision(SecurityReasonCode.INVALID_CONTEXT)

        # Step 2: Validate Tool Name
        tool = proposal.tool
        if not isinstance(tool, ToolName):
            try:
                tool = ToolName(tool)
            except (ValueError, KeyError):
                return make_rejection_decision(SecurityReasonCode.UNKNOWN_TOOL)

        # Step 3: Validate Tool Arguments against Canonical Schemas
        # Rejects unexpected extra fields, incorrect types, negative amounts, etc.
        try:
            validated_args = validate_tool_arguments(tool, proposal.arguments)
        except (ValidationError, ValueError, TypeError, KeyError) as err:
            logger.warning(
                "Proposal %s rejected due to invalid tool arguments: %s",
                getattr(proposal, "proposal_id", "unknown"),
                err,
            )
            return make_rejection_decision(SecurityReasonCode.INVALID_TOOL_ARGUMENTS)

        # Step 4: Account Lock Enforcement
        # State-changing operations are strictly forbidden on locked accounts (T11)
        if context.account_locked:
            if is_mutation_tool(tool) or config.lock_denies_read_only:
                return make_rejection_decision(SecurityReasonCode.ACCOUNT_LOCKED)

        # Step 5: Account Ownership & Tenancy Verification
        # Ensure proposals cannot access or move funds from unauthenticated accounts
        if config.enforce_account_matching:
            if hasattr(validated_args, "source_account_id"):
                if validated_args.source_account_id != context.account_id:
                    return make_rejection_decision(
                        SecurityReasonCode.SOURCE_ACCOUNT_MISMATCH
                    )
            elif hasattr(validated_args, "account_id"):
                if validated_args.account_id != context.account_id:
                    return make_rejection_decision(
                        SecurityReasonCode.ACCOUNT_MISMATCH
                    )

        # Step 6: Policy Tier Determination
        if is_read_only_tool(tool):
            # Read-only queries: Tier GREEN, automatic, no confirmation required (T01)
            return PolicyDecision(
                tier=Tier.GREEN,
                allowed_to_proceed=True,
                requires_confirmation=False,
                requires_mfa=False,
                reason_code=SecurityReasonCode.READ_ONLY_ACCESS,
            )

        if tool == ToolName.REQUEST_SUBSCRIPTION_CANCEL:
            # Subscription cancellation: Tier YELLOW, requires explicit confirmation (T07)
            return PolicyDecision(
                tier=Tier.YELLOW,
                allowed_to_proceed=True,
                requires_confirmation=True,
                requires_mfa=False,
                reason_code=SecurityReasonCode.SUBSCRIPTION_CANCEL_CONFIRMATION_REQUIRED,
            )

        if tool == ToolName.REQUEST_TRANSFER:
            # Transfer amount and cumulative threshold evaluation
            amount = validated_args.amount
            if amount <= Decimal("0.00"):
                return make_rejection_decision(
                    SecurityReasonCode.INVALID_TOOL_ARGUMENTS
                )

            cumulative_daily_total = context.daily_transfer_total + amount

            if cumulative_daily_total <= config.daily_transfer_threshold:
                # Cumulative daily total <= CNY 1,000: Tier YELLOW, confirmation required (T02)
                return PolicyDecision(
                    tier=Tier.YELLOW,
                    allowed_to_proceed=True,
                    requires_confirmation=True,
                    requires_mfa=False,
                    reason_code=SecurityReasonCode.TRANSFER_WITHIN_DAILY_LIMIT,
                )
            else:
                # Cumulative daily total > CNY 1,000: Tier RED, confirmation + MFA required (T03)
                return PolicyDecision(
                    tier=Tier.RED,
                    allowed_to_proceed=True,
                    requires_confirmation=True,
                    requires_mfa=True,
                    reason_code=SecurityReasonCode.TRANSFER_EXCEEDS_DAILY_LIMIT,
                )

        # Unhandled tool falls closed
        return make_rejection_decision(SecurityReasonCode.UNKNOWN_TOOL)

    except Exception as exc:  # pylint: disable=broad-except
        # Absolute fail-closed guarantee: any unexpected runtime failure is caught
        logger.error("Unexpected exception during policy evaluation: %s", exc)
        return make_rejection_decision(SecurityReasonCode.INTERNAL_POLICY_ERROR)
